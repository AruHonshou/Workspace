const base = Date.parse("2026-08-17T15:00:00Z");

function event(
  sequence: number,
  type: string,
  stage: string,
  actorKind: GraphEvent["actor_kind"],
  actorId: string,
  templateKey: string,
  templateArgs: Record<string, string | number | boolean> = {},
  payload: Record<string, unknown> = {},
  targetId?: string,
): GraphEvent {
  return {
    schema_version: "1.0",
    event_id: `demo-event-${sequence}`,
    run_id: runId,
    sequence,
    timestamp: new Date(base + sequence * 1_100).toISOString(),
    type,
    stage,
    actor_kind: actorKind,
    actor_id: actorId,
    target_id: targetId,
    entity_ref: null,
    causation_id: sequence > 1 ? `demo-event-${sequence - 1}` : null,
    payload,
    visibility: "user",
    ui: { template_key: templateKey, template_args: templateArgs, severity: "info" },
  };
}

